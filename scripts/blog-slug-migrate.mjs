#!/usr/bin/env node
/**
 * Generate semantic URL slugs for the migrated SegmentFault posts
 * (filenames like `sf-1190000007281165.md` → SEO-friendly slugs).
 *
 * How it works
 * ------------
 * Astro reserves the `slug` frontmatter field: setting it overrides the
 * filename-derived entry.slug, so the published URL becomes /blog/<slug>/ with
 * zero file renames. This script:
 *   1. finds every `sf-*` blog post that has no `slug` override yet,
 *   2. derives a semantic slug from its Chinese/English title,
 *   3. resolves collisions,
 *   4. (dry-run by default) prints the mapping and writes a 301 redirect map.
 *
 * The OLD /blog/sf-<id>/ URLs stop existing once `slug` is set, so a 301 must
 * be deployed (see deploy/nginx/blog-sf-redirects.conf) to preserve links.
 *
 * Usage
 *   node scripts/blog-slug-migrate.mjs            # dry run, print mapping
 *   node scripts/blog-slug-migrate.mjs --apply    # write slug: into frontmatter
 *                                                # + emit nginx + json maps
 */

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const blogDir = join(root, "apps/web/src/content/blog");
const outNginx = join(root, "deploy/nginx/blog-sf-redirects.conf");
const outJson = join(root, "scripts/data/blog-slug-map.json");

const SITE = (process.env.PUBLIC_BASE_URL || "https://www.lilnong.top").replace(/\/$/, "");
const APPLY = process.argv.includes("--apply");
const MAX_LEN = 80;

/** @param {string} title */
function slugifyTitle(title) {
  if (!title) return "";
  return String(title)
    .trim()
    .toLowerCase()
    // keep CJK, letters, digits, spaces and hyphens; drop punctuation
    .replace(/[^\p{Script=Han}\p{L}\p{N}\s-]/gu, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, MAX_LEN);
}

function hasSlugField(raw) {
  return /^slug:\s*/m.test(raw);
}

function frontmatterTitle(raw) {
  const m = raw.match(/^title:\s*["'](.+?)["']\s*$/m) || raw.match(/^title:\s*(.+)\s*$/m);
  return m ? m[1].trim() : "";
}

function insertSlug(raw, semantic) {
  return raw.replace(/^---\r?\n/, `---\nslug: "${semantic}"\n`);
}

// ---- gather all posts ---------------------------------------------------
const files = readdirSync(blogDir).filter((f) => /\.mdx?$/.test(f));
const existingSlugs = new Set(); // final URL slug each post will occupy
for (const file of files) {
  const raw = readFileSync(join(blogDir, file), "utf8");
  const oldSlug = file.replace(/\.mdx?$/, "");
  const m = raw.match(/^slug:\s*["']?(.+?)["']?\s*$/m);
  existingSlugs.add(m ? m[1].trim() : oldSlug);
}

// ---- compute semantic slugs for sf- posts -------------------------------
const mapping = [];
const used = new Set(existingSlugs);
const collisions = [];

for (const file of files) {
  const oldSlug = file.replace(/\.mdx?$/, "");
  if (!oldSlug.startsWith("sf-")) continue;
  const raw = readFileSync(join(blogDir, file), "utf8");
  if (hasSlugField(raw)) continue; // already migrated

  const title = frontmatterTitle(raw);
  let base = slugifyTitle(title);
  if (!base) {
    base = oldSlug; // fallback: keep as-is if title empty
  }
  let candidate = base;
  let n = 2;
  while (used.has(candidate)) {
    candidate = `${base}-${n++}`;
    collisions.push({ file, title, collisionWith: candidate });
  }
  used.add(candidate);
  mapping.push({ file, oldSlug, newSlug: candidate, title });
}

// ---- output -------------------------------------------------------------
console.log(`Site: ${SITE}`);
console.log(`SF posts to migrate: ${mapping.length}`);
console.log(`Collisions resolved: ${collisions.length}`);
console.log("\nSample mapping (first 25):");
for (const m of mapping.slice(0, 25)) {
  console.log(`  /blog/${m.oldSlug}/  →  /blog/${m.newSlug}/   (${m.title})`);
}
if (mapping.length > 25) console.log(`  ... and ${mapping.length - 25} more`);

if (!APPLY) {
  console.log("\nDRY RUN — no files changed. Re-run with --apply to write changes.");
  process.exit(0);
}

// ---- apply --------------------------------------------------------------
let written = 0;
for (const m of mapping) {
  const path = join(blogDir, m.file);
  const raw = readFileSync(path, "utf8");
  writeFileSync(path, insertSlug(raw, m.newSlug), "utf8");
  written++;
}

mkdirSync(dirname(outNginx), { recursive: true });
mkdirSync(dirname(outJson), { recursive: true });

const nginx = [
  "# AUTO-GENERATED by scripts/blog-slug-migrate.mjs --apply",
  "# 301 redirects: old sf- URLs → semantic slugs. Include this from the",
  "# lilnong.top server block, e.g. `include /etc/nginx/conf.d/blog-sf-redirects.conf;`.",
  "",
  ...mapping.map(
    (m) =>
      `location = /blog/${m.oldSlug}/ { return 301 ${SITE}/blog/${m.newSlug}/; }`,
  ),
  "",
].join("\n");
writeFileSync(outNginx, nginx, "utf8");

const json = mapping.map((m) => ({
  from: `/blog/${m.oldSlug}/`,
  to: `/blog/${m.newSlug}/`,
  title: m.title,
}));
writeFileSync(outJson, JSON.stringify(json, null, 2), "utf8");

console.log(`\nApplied: wrote slug: into ${written} files.`);
console.log(`Wrote ${outNginx}`);
console.log(`Wrote ${outJson}`);
console.log("\nNext: rebuild, copy blog-sf-redirects.conf to the server and `include` it,");
console.log("then `nginx -t && systemctl reload nginx`.");
